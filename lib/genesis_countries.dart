String genesisCountryLabel(String? code) {
  if (code == null || code.isEmpty) {
    return GenesisLanguage.copy('Wybierz kraj', 'Choose a country');
  }
  for (final country in genesisCountries) {
    if (country.code == code.toUpperCase()) {
      return '${country.label} (${country.code})';
    }
  }
  return code;
}

Future<String?> genesisPickCountry(BuildContext context, String? current) async {
  final search = TextEditingController();
  var query = '';
  try {
    return await showModalBottomSheet<String>(
      context: context,
      isScrollControlled: true,
      showDragHandle: true,
      builder: (sheetContext) => StatefulBuilder(
        builder: (sheetContext, update) {
          final filtered = genesisCountries.where((c) =>
            c.code.toLowerCase().contains(query) ||
            c.pl.toLowerCase().contains(query) ||
            c.en.toLowerCase().contains(query)).toList()
              ..sort((a, b) => a.label.compareTo(b.label));
          return SafeArea(
            child: Padding(
              padding: EdgeInsets.only(
                bottom: MediaQuery.viewInsetsOf(sheetContext).bottom),
              child: SizedBox(
                height: MediaQuery.sizeOf(sheetContext).height * .76,
                child: Column(children: [
                  Padding(
                    padding: const EdgeInsets.fromLTRB(18, 4, 18, 12),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        Text(GenesisLanguage.copy(
                          'WYBIERZ KRAJ', 'CHOOSE COUNTRY'),
                          style: const TextStyle(
                            fontSize: 18, fontWeight: FontWeight.bold)),
                        const SizedBox(height: 12),
                        TextField(
                          controller: search,
                          autofocus: true,
                          onChanged: (v) => update(() => query = v.trim().toLowerCase()),
                          decoration: InputDecoration(
                            prefixIcon: const Icon(Icons.search),
                            hintText: GenesisLanguage.copy(
                              'Szukaj kraju lub kodu…',
                              'Search country or code…'),
                            border: const OutlineInputBorder())),
                      ]),
                  ),
                  Expanded(child: ListView.builder(
                    itemCount: filtered.length + 1,
                    itemBuilder: (context, i) {
                      if (i == 0) {
                        return ListTile(
                          leading: const Icon(Icons.public_off_outlined),
                          title: Text(GenesisLanguage.copy(
                            'Nie podawaj kraju', 'Do not specify country')),
                          onTap: () => Navigator.of(sheetContext).pop(''));
                      }
                      final c = filtered[i - 1];
                      return ListTile(
                        title: Text(c.label),
                        subtitle: Text(c.code),
                        trailing: c.code == current
                          ? const Icon(Icons.check) : null,
                        onTap: () => Navigator.of(sheetContext).pop(c.code),
                      );
                    },
                  )),
                ]),
              ),
            ),
          );
        },
      ),
    );
  } finally {
    search.dispose();
  }
}
